export const translate = (lang: Lang, key: Key, ...args: (string | number)[]) => {
  let s: string = DICT[lang][key] ?? DICT.ar[key] ?? key;
  args.forEach((a, i) => { s = s.replace(`{${i}}`, String(a)); });
  return s;
};

